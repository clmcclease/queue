// Independent QA: #85 / Q7. Exercise the actual client with JSON-number boundary ids.
import assert from "node:assert/strict";
import { after, afterEach, before, test } from "node:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";
import { clearMocks, mockIPC } from "@tauri-apps/api/mocks";
import { createServer } from "vite";

let server, client, cache;
const dom = new JSDOM("<!doctype html>");
globalThis.window = dom.window;
before(async () => {
  cache = await mkdtemp(join(tmpdir(), "queue-85-vite-"));
  server = await createServer({
    root: fileURLToPath(new URL("../../", import.meta.url)),
    cacheDir: cache, configFile: false, logLevel: "silent", appType: "custom",
    server: { middlewareMode: true, hmr: false, watch: null },
  });
  client = await server.ssrLoadModule("/src/queue.ts");
});
afterEach(() => clearMocks());
after(async () => {
  await server?.close();
  if (cache) await rm(cache, { recursive: true, force: true });
  dom.window.close();
  delete globalThis.window;
});

// Literal JSON numbers, as sent by serde/Tauri, rather than ids generated by JS arithmetic.
const rows = () => JSON.parse(`[
  {"id":9007199254740991,"url":"https://e.test/last","rev":1,"status":{"state":"queued"}},
  {"id":9007199254740990,"url":"https://e.test/previous","rev":1,"status":{"state":"queued"}}
]`);

test("#85: adjacent safe-limit ids survive JSON, sorting and independent revision merges", () => {
  const [last, previous] = rows();
  for (const row of [last, previous]) assert.ok(Number.isSafeInteger(row.id));
  let shown = client.mergeItems([], [last, previous]);
  assert.deepEqual(shown.map((r) => r.id), [9007199254740990, 9007199254740991]);
  shown = client.mergeItems(shown, [{ ...last, rev: 3, name: "日本語 é" }]);
  shown = client.mergeItems(shown, [{ ...last, rev: 2, name: "stale" }]);
  assert.equal(shown.length, 2);
  assert.equal(shown[0], previous);
  assert.equal(shown[1].name, "日本語 é");
});

test("#85: removing one boundary id doesn't suppress its adjacent row", () => {
  const [last, previous] = rows();
  const shown = client.mergeItems([previous], [last, { ...previous, rev: 2 }], new Set([last.id]));
  assert.deepEqual(shown.map((r) => r.id), [previous.id]);
  assert.equal(shown[0].rev, 2);
});

test("#85: every row-addressed IPC command preserves the exact boundary id", async () => {
  const calls = [];
  mockIPC((command, args) => { calls.push({ command, args }); return null; });
  for (const { id } of rows()) {
    await client.downloadItem(id);
    await client.cancelItem(id);
    await client.removeItem(id);
    await client.retryItem(id);
    await client.revealDownload(id);
    await client.renameItem(id, "NUL 日本語");
  }
  assert.deepEqual(calls, rows().flatMap(({ id }) => [
    { command: "queue_download", args: { id } },
    { command: "queue_cancel", args: { id } },
    { command: "queue_remove", args: { id } },
    { command: "queue_retry", args: { id } },
    { command: "reveal_download", args: { id } },
    { command: "queue_rename", args: { id, name: "NUL 日本語" } },
  ]));
});
